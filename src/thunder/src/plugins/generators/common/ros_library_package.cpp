void write_file(const fs::path& path, const std::string& content) {
    fs::create_directories(path.parent_path());
    std::ofstream output(path);
    if (!output) throw std::runtime_error("Unable to write generated file: " + path.string());
    output << content;
}

std::string package_xml(const std::string& package_name, const std::string& robot_name) {
    return  "<?xml version=\"1.0\"?>\n"
            "<package format=\"3\">\n"
            "  <name>" + package_name + "</name>\n"
            "  <version>0.1.0</version>\n"
            "  <description>C++ library of the robot " + robot_name + ", generated by Thunder Dynamics. "
            "Do not edit: regenerate.</description>\n"
            "  <maintainer email=\"maintainer@example.com\">Thunder Dynamics</maintainer>\n"
            "  <license>Apache-2.0</license>\n"
            "  <buildtool_depend>ament_cmake</buildtool_depend>\n"
            "  <depend>eigen</depend>\n"
            "  <depend>yaml-cpp</depend>\n"
            "  <export>\n"
            "    <build_type>ament_cmake</build_type>\n"
            "  </export>\n"
            "</package>\n";
}

std::string cmake_lists(const std::string& package_name, const std::string& robot_name) {
    const std::string gen_cpp = "src/" + robot_name + "_gen.cpp";
    return  "cmake_minimum_required(VERSION 3.16)\n"
            "project(" + package_name + ")\n\n"
            "if(NOT CMAKE_BUILD_TYPE)\n"
            "  set(CMAKE_BUILD_TYPE Release)\n"
            "endif()\n\n"
            "find_package(ament_cmake REQUIRED)\n"
            "find_package(Eigen3 REQUIRED)\n"
            "find_package(yaml-cpp REQUIRED)\n\n"
            "add_library(${PROJECT_NAME} SHARED\n"
            "  src/thunder_" + robot_name + ".cpp\n"
            "  " + gen_cpp + "\n"
            ")\n"
            "target_compile_features(${PROJECT_NAME} PUBLIC cxx_std_17)\n"
            "# Consumers include <" + package_name + "/thunder_" + robot_name + ".h>; the generated sources include\n"
            "# their headers without the package prefix, hence the private entry.\n"
            "target_include_directories(${PROJECT_NAME}\n"
            "  PUBLIC\n"
            "    $<BUILD_INTERFACE:${CMAKE_CURRENT_SOURCE_DIR}/include>\n"
            "    $<INSTALL_INTERFACE:include>\n"
            "  PRIVATE\n"
            "    ${CMAKE_CURRENT_SOURCE_DIR}/include/${PROJECT_NAME}\n"
            ")\n"
            "target_link_libraries(${PROJECT_NAME} PUBLIC Eigen3::Eigen yaml-cpp)\n\n"
            "# The CasADi code can be a very large translation unit: -O2 by default, which keeps it fast without\n"
            "# the compile time and memory of -O3. Change it with\n"
            "#   colcon build --packages-select " + package_name + " --cmake-args \"-DTHUNDER_GEN_OPTIONS=-O3;-march=native\"\n"
            "set(THUNDER_GEN_OPTIONS \"-O2\" CACHE STRING\n"
            "  \"Compile options for the generated " + robot_name + "_gen.cpp (a ;-separated list)\")\n"
            "set_source_files_properties(" + gen_cpp + " PROPERTIES COMPILE_OPTIONS \"${THUNDER_GEN_OPTIONS}\")\n\n"
            "install(DIRECTORY include/ DESTINATION include)\n"
            "install(DIRECTORY config DESTINATION share/${PROJECT_NAME})\n"
            "install(TARGETS ${PROJECT_NAME} EXPORT export_${PROJECT_NAME}\n"
            "  ARCHIVE DESTINATION lib\n"
            "  LIBRARY DESTINATION lib\n"
            "  RUNTIME DESTINATION bin\n"
            ")\n\n"
            "ament_export_targets(export_${PROJECT_NAME} HAS_LIBRARY_TARGET)\n"
            "ament_export_dependencies(Eigen3 yaml-cpp)\n"
            "ament_package()\n";
}

