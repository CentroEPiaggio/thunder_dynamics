std::string ros_library_package_name(const std::string& robot_name) {
    const std::string name = "thunder_" + boost::algorithm::to_lower_copy(robot_name);
    const bool valid = std::all_of(name.begin(), name.end(), [](unsigned char character) {
        return std::islower(character) || std::isdigit(character) || character == '_';
    });
    if (!valid) {
        throw std::runtime_error("ROS 2 package names must be lowercase letters, digits, and underscores. Robot name '" +
                                 robot_name + "' cannot produce a standard package name.");
    }
    return name;
}

std::string write_ros_library_package(const fs::path& output_root, const std::string& robot_name,
                                      const std::string& generator) {
    const std::string package_name = ros_library_package_name(robot_name);
    const fs::path package_root = output_root / package_name;
    if (fs::exists(output_root / "pyproject.toml")) {
        throw std::runtime_error(generator + " cannot use a Python-enabled robot_generator output. Set robot_generator.gen_python to false.");
    }

    // source in output_root (written by robot_generator) -> destination in the package
    const std::vector<std::pair<std::string, fs::path>> files = {
        {"thunder_" + robot_name + ".h", fs::path("include") / package_name / ("thunder_" + robot_name + ".h")},
        {robot_name + "_gen.h", fs::path("include") / package_name / (robot_name + "_gen.h")},
        {"thunder_" + robot_name + ".cpp", fs::path("src") / ("thunder_" + robot_name + ".cpp")},
        {robot_name + "_gen.cpp", fs::path("src") / (robot_name + "_gen.cpp")},
        {robot_name + "_conf.yaml", fs::path("config") / (robot_name + "_conf.yaml")},
        {robot_name + "_par.yaml", fs::path("config") / (robot_name + "_par.yaml")},
    };
    for (const auto& [source, destination] : files) {
        if (!fs::exists(output_root / source)) {
            throw std::runtime_error("Missing " + (output_root / source).string() + ". " + generator +
                                     " requires robot_generator to run first with gen_robot: true.");
        }
        fs::create_directories((package_root / destination).parent_path());
        fs::copy_file(output_root / source, package_root / destination, fs::copy_options::overwrite_existing);
    }
    write_file(package_root / "package.xml", package_xml(package_name, robot_name));
    write_file(package_root / "CMakeLists.txt", cmake_lists(package_name, robot_name));
    return package_name;
}

